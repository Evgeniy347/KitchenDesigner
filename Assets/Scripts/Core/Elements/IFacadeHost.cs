namespace KitchenDesigner.Core
{
    /// <summary>
    /// Элемент, которому мебельный фасад ПРИСТЁГИВАЕТСЯ отдельным элементом, а не
    /// входит в его собственную модель: ящик и полновстраиваемая посудомоечная
    /// машина. Своей фасадной панели у таких приборов нет — лицо им делает
    /// фасад кухни, и связь держится на ИМЕНИ фасада (переживает сохранение,
    /// чинится при переименовании, у удалённого фасада просто не находится).
    ///
    /// Интерфейс, а не два одинаковых поля: на «кто ссылается на этот фасад»
    /// завязаны <see cref="DrawerLinks.Rename"/>, окно свойств и анализатор
    /// сцены — с двумя типами хозяев эти места иначе разошлись бы по копипасте.
    /// </summary>
    public interface IFacadeHost
    {
        /// <summary>Имя прикреплённого фасада; пусто — фасада нет.</summary>
        string AttachedFacadeName { get; set; }

        /// <summary>Прикреплённый фасад, либо null (удалён или не найден).</summary>
        FacadeElement? FindAttachedFacade();
    }
}
