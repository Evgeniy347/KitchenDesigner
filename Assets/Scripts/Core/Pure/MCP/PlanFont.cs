        private static readonly byte[]?[] Glyphs = Parse();

        public static IEnumerable<char> Known
        {
            get
            {
                for (int code = 0; code < Glyphs.Length; code++)
                    if (Glyphs[code] != null) yield return (char)code;
            }
        }

        public static bool Has(char c) => c < Glyphs.Length && Glyphs[c] != null;

        public static byte[] RowsOf(char c) => Has(c) ? Glyphs[c]! : Glyphs[Unknown]!;

        public static bool IsSet(char c, int column, int row) => (RowsOf(c)[row] >> (Columns - 1 - column) & 1) != 0;

        private static byte[]?[] Parse()
        {
            var glyphs = new byte[]?[AsciiLimit];
            foreach (var line in Table.Split('\n'))
            {
                var rows = line.Substring(2).Split('/');
                var bits = new byte[Rows];
                for (int r = 0; r < Rows; r++)
                    for (int c = 0; c < Columns; c++)
                        if (rows[r][c] == '#') bits[r] |= (byte)(1 << (Columns - 1 - c));
                glyphs[line[0]] = bits;
            }
            return glyphs;
        }
