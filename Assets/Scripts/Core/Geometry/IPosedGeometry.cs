using UnityEngine;

namespace KitchenDesigner.Core
{
    /// <summary>Источник геометрии детали для ПРОИЗВОЛЬНОЙ позиции.
    ///
    /// Снэп примеряет деталь в разные позиции (основной проход и два добора),
    /// и сдвинуть готовый снимок нельзя: у открытой дверцы и выдвинутого ящика
    /// поза заморожена, у мойки приподнята на половину бортика, у опущенной
    /// стены высота берётся полная. Эти правила знает только сам элемент —
    /// ядро спрашивает у него готовую геометрию и остаётся чистым.</summary>
    public interface IPosedGeometry
    {
        ElementGeometry At(Vector3 position);
    }
}
