using System.Collections.Generic;

public static class Wgl4CharSet
{
    private static readonly HashSet<int> Points = Build();

    public static bool Contains(char c) => Points.Contains(c);

    private static HashSet<int> Build()
    {
        var set = new HashSet<int>();
        void Range(int from, int to) { for (int c = from; c <= to; c++) set.Add(c); }
        void Only(params int[] cs) { foreach (int c in cs) set.Add(c); }

        Range(0x0020, 0x007E);
        Range(0x00A0, 0x00FF);
        Range(0x0100, 0x017F);
        Range(0x0384, 0x03CE);
        Range(0x0400, 0x045F);
        Only(0x0192, 0x02C6, 0x02C7, 0x02C9, 0x02D8, 0x02D9, 0x02DA, 0x02DB, 0x02DC, 0x02DD,
            0x0490, 0x0491);
        Only(0x2013, 0x2014, 0x2015, 0x2017, 0x2018, 0x2019, 0x201A, 0x201B, 0x201C, 0x201D,
            0x201E, 0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2032, 0x2033, 0x2039, 0x203A,
            0x203C, 0x2044, 0x207F, 0x20A3, 0x20A4, 0x20A7, 0x20AC);
        Only(0x2105, 0x2113, 0x2116, 0x2122, 0x2126, 0x212E, 0x215B, 0x215C, 0x215D, 0x215E);
        Range(0x2190, 0x2195);
        Only(0x21A8);
        Only(0x2202, 0x2206, 0x220F, 0x2211, 0x2212, 0x2215, 0x2219, 0x221A, 0x221E, 0x221F,
            0x2229, 0x222B, 0x2248, 0x2260, 0x2261, 0x2264, 0x2265, 0x2302, 0x2310, 0x2320,
            0x2321);
        Only(0x2500, 0x2502, 0x250C, 0x2510, 0x2514, 0x2518, 0x251C, 0x2524, 0x252C, 0x2534,
            0x253C);
        Range(0x2550, 0x256C);
        Only(0x2580, 0x2584, 0x2588, 0x258C, 0x2590, 0x2591, 0x2592, 0x2593);
        Only(0x25A0, 0x25A1, 0x25AA, 0x25AB, 0x25AC, 0x25B2, 0x25BA, 0x25BC, 0x25C4, 0x25CA,
            0x25CB, 0x25CF, 0x25D8, 0x25D9, 0x25E6);
        Only(0x263A, 0x263B, 0x263C, 0x2640, 0x2642, 0x2660, 0x2663, 0x2665, 0x2666, 0x266A,
            0x266B);
        Only(0xFB01, 0xFB02, 0xFFFD);
        return set;
    }
}
