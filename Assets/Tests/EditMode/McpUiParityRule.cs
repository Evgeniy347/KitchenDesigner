/// <summary>Общая преамбула сообщений всех сторожей паритета UI и MCP.
///
/// Она существует не для красоты. Красное сообщение этих сторожей читает не
/// человек, а агент, которого попросили сделать что-то другое — добавить
/// свойство, завести тип, поправить панель. Увидев чужое на вид расхождение,
/// он останавливается и спрашивает: «а нужно ли это чинить, такой задачи не
/// стояло?» — и работа встаёт на ровном месте, потому что вопрос обращён к
/// человеку, которого рядом может не быть.
///
/// Ответ на этот вопрос один и тот же всегда, поэтому он написан прямо в
/// сообщении, до всякой техники: правило проекта, а не находка теста; часть
/// той же правки, а не отдельная задача; разрешения не требует. Дальше идёт
/// адрес — какие два файла открыть, — и только потом список расхождений.
///
/// Текст один на все сторожа: правило одно, и разночтения между четырьмя его
/// пересказами — это ровно тот дефект, который эти сторожа и ловят.</summary>
internal static class McpUiParityRule
{
    /// <summary>Правило. Стоит первым в каждом сообщении.</summary>
    public const string Rule =
        "ПРАВИЛО ПРОЕКТА: всё, что пользователь может изменить или создать в интерфейсе, "
        + "обязано быть доступно и через MCP, и наоборот. Это НЕ отдельная задача и НЕ "
        + "предмет согласования: если правка открыла что-то одной поверхности, открыть это "
        + "второй входит в ту же правку. Чинить здесь и сейчас, разрешения не спрашивать. "
        + "Спросить стоит ровно об одном — когда расхождение выглядит осознанным решением о "
        + "продукте; тогда оно закрывается не кодом, а записью с причиной в списке "
        + "исключений этого теста. ";

    /// <summary>Куда идти за правкой свойства. Оба адреса вместе: агент,
    /// пришедший с любой стороны, должен видеть обе.</summary>
    public const string PropertyAddresses =
        "Адреса: строка панели — Assets/Scripts/Core/UI/*FieldsEditor.cs (или ContextMenuUI "
        + "для общих строк); проволочное поле — поле в EditOp "
        + "(Assets/Scripts/Core/MCP/Contract/McpToolParams.cs), разрешение в "
        + "Assets/Scripts/Core/MCP/EditFieldRules.cs и правка в "
        + "Assets/Scripts/Core/MCP/ElementEditAppliers.cs. Порядок шагов — AGENTS.md → "
        + "«New property checklist». ";

    /// <summary>Куда идти за созданием элемента.</summary>
    public const string CreationAddresses =
        "Адреса: кнопка сайдбара — перечень в Assets/Scripts/Core/UI/SidebarCatalog.cs, "
        + "вызов фабрики в Assets/Scripts/Core/UI/ElementSpawner.cs; создание агентом — тип "
        + "в CreateItem.type (Assets/Scripts/Core/MCP/Contract/McpToolParams.cs) и ветка в "
        + "ElementSpawners.ByType (Assets/Scripts/Core/MCP/ElementSpawners.cs). ";

    /// <summary>Куда идти за настройкой. Таблица одна, и из неё живут обе
    /// стороны — поэтому адрес тут короче остальных.</summary>
    public const string SettingAddresses =
        "Адреса: строка панели — Assets/Scripts/Core/UI/Settings*Tab.cs; ключ агента — "
        + "таблица SettingKeys.All (Assets/Scripts/Core/MCP/SettingKeys.cs), откуда "
        + "set_setting и get_settings берут его сами, плюс тот же ключ в перечислении "
        + "ParamsSetSetting.name и в описании инструмента set_setting "
        + "(Assets/Scripts/Core/MCP/Contract/). ";
}
